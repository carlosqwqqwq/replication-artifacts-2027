_RECORDED_PATH_RE = re.compile(rb'/[A-Za-z0-9_./-]+')
_LLVM_KNOWN_NONFATAL_WARNING_RE = re.compile(
    r"^(?:warning: \d+ functions have mismatched data$|"
    r"warning: .+: invalid instrumentation profile data "
    r"\(file header is corrupt\)$)"
)


def _recorded_source_dirs(build_root: Path) -> tuple[str, ...]:
    "从 .gcno 提取构建时记录的源码根路径，供 gcovr 建别名。"
    roots: dict[str, int] = {}
    for path in build_root.rglob("*.gcno"):
        try:
            data = path.read_bytes()
        except OSError:
            continue
        for raw in _RECORDED_PATH_RE.findall(data):
            value = raw.decode("utf-8", "replace")
            # 只处理构建容器内的 /work 路径；宿主路径在其他调用点已可用。
            if not value.startswith("/work/"):
                continue
            segments = [seg for seg in value.split("/") if seg]
            if len(segments) < 2:
                continue
            head = "/" + "/".join(segments[:2])
            # These are build/container output roots, not source roots; do not
            # turn them into aliases while retaining every candidate source root.
            if segments[1] in {"build", "tmp", "cache", "out"}:
                continue
            roots[head] = roots.get(head, 0) + 1
    return tuple(sorted(roots, key=lambda k: (-roots[k], k)))


def _write_gcov_json_lcov(
    json_files: list[Path], profile: Path, source_root: Path,
    accumulator: tuple[dict[tuple[str, int, str], int],
                       dict[tuple[str, int], int],
                       dict[tuple[str, int, int], int]] | None = None,
    *, finalize: bool = True,
) -> tuple[int, str]:
    """Convert GCC's stdlib JSON report to the small LCOV subset we consume."""
    # GCC can report same-named functions in one translation unit.  Include
    # the declaration line in the merge key so their denominator and hits stay
    # separate in the generated LCOV profile.
    functions, lines, branches = accumulator or ({}, {}, {})

    def source_path(value: object) -> str | None:
        if not isinstance(value, str) or not value:
            return None
        path = Path(value)
        if path.is_absolute() and path.is_file():
            return str(path.resolve())
        if path.is_absolute() and source_root.name in path.parts:
            suffix = path.parts[path.parts.index(source_root.name) + 1:]
            candidate = source_root.joinpath(*suffix)
            if candidate.is_file():
                return str(candidate.resolve())
        candidates = (source_root / path, source_root.parent / path)
        for candidate in candidates:
            if candidate.is_file():
                return str(candidate.resolve())
        return str((source_root / path).resolve())

    try:
        for report in json_files:
            with gzip.open(report, "rt", encoding="utf-8") as stream:
                payload = json.load(stream)
            if not isinstance(payload, dict):
                return 2, "gcov-json-root-invalid"
            files = payload.get("files", ())
            if not isinstance(files, (list, tuple)):
                return 2, "gcov-json-files-invalid"
            for item in files:
                source = source_path(item.get("file")) if isinstance(item, dict) else None
                if source is None:
                    continue
                for function in item.get("functions", ()):
                    if not isinstance(function, dict) or not isinstance(function.get("name"), str):
                        continue
                    line = _hit_count(function.get("start_line", 0))
                    key = (source, line, function["name"])
                    value = _hit_count(function.get("execution_count", 0))
                    functions[key] = max(functions.get(key, 0), value)
                for line in item.get("lines", ()):
                    if not isinstance(line, dict):
                        continue
                    number = _hit_count(line.get("line_number", 0))
                    key = (source, number)
                    line_count = line.get("count", 0)
                    # GCC's JSON uses -1 for an unexecuted line in some
                    # gcov versions.  LCOV represents the same fact as a
                    # zero hit count; rejecting it makes an otherwise valid
                    # cell fail after the profile merge has already passed.
                    if (
                        isinstance(line_count, (int, float))
                        and not isinstance(line_count, bool)
                        and line_count < 0
                    ) or (
                        isinstance(line_count, str)
                        and line_count.strip().startswith("-")
                    ):
                        line_count = 0
                    lines[key] = max(lines.get(key, 0), _hit_count(line_count))
                    for index, branch in enumerate(line.get("branches", ())):
                        if isinstance(branch, dict):
                            # GCC's JSON format uses negative sentinels for
                            # branches that were not executed (the exact
                            # value differs across GCC versions, e.g. -1 and
                            # -2). LCOV represents the same fact as ``-``;
                            # treating every negative sentinel as zero
                            # preserves the branch denominator without
                            # turning a valid report into a collector error.
                            branch_count = branch.get("count", 0)
                            if (
                                isinstance(branch_count, (int, float))
                                and not isinstance(branch_count, bool)
                                and branch_count < 0
                            ) or (
                                isinstance(branch_count, str)
                                and branch_count.strip().startswith("-")
                            ):
                                branch_count = 0
                            branches[(source, number, index)] = max(
                                branches.get((source, number, index), 0),
                                _hit_count(branch_count),
                            )
    except (OSError, UnicodeError, ValueError, json.JSONDecodeError) as exc:
        return 2, f"gcov-json-error:{type(exc).__name__}"
    if not finalize:
        return 0, ""
    if not functions and not lines and not branches:
        return 2, "gcov-json-records-missing"

    profile.parent.mkdir(parents=True, exist_ok=True)
    sources = sorted({key[0] for key in (*functions, *lines, *branches)})
    with profile.open("w", encoding="utf-8") as stream:
        for source in sources:
            stream.write(f"TN:\nSF:{source}\n")
            source_functions = sorted(key for key in functions if key[0] == source)
            for key in source_functions:
                stream.write(f"FN:{key[1]},{key[2]}\n")
            for key in source_functions:
                stream.write(f"FNDA:{functions[key]},{key[2]}\n")
            stream.write(f"FNF:{len(source_functions)}\n")
            stream.write(f"FNH:{sum(functions[key] > 0 for key in source_functions)}\n")
            source_lines = sorted(key for key in lines if key[0] == source)
            for _, number in source_lines:
                stream.write(f"DA:{number},{lines[(source, number)]}\n")
            stream.write(f"LF:{len(source_lines)}\n")
            stream.write(f"LH:{sum(lines[key] > 0 for key in source_lines)}\n")
            source_branches = sorted(key for key in branches if key[0] == source)
            for _, number, index in source_branches:
                hits = branches[(source, number, index)]
                stream.write(f"BRDA:{number},-,{index},{hits or '-'}\n")
            stream.write(f"BRF:{len(source_branches)}\n")
            stream.write(f"BRH:{sum(branches[key] > 0 for key in source_branches)}\n")
            stream.write("end_of_record\n")
    return 0, ""


def _merge_gcov_case_roots(
    case_roots: list[Path], merge_tool: str, staging: Path,
) -> tuple[int, str, Path | None]:
    """Merge case counters in a balanced tree, keeping raw cases untouched."""
    level_roots = list(case_roots)
    generated_roots: set[Path] = set()
    level = 0
    while len(level_roots) > 1:
        staging.mkdir(parents=True, exist_ok=True)
        next_roots: list[Path] = []
        pair_tasks: list[tuple[Path, Path, Path]] = []
        for offset in range(0, len(level_roots), 2):
            left = level_roots[offset]
            if offset + 1 >= len(level_roots):
                next_roots.append(left)
                continue
            right = level_roots[offset + 1]
            pair_tasks.append((
                left, right,
                staging / f"merge-{level:04d}-{offset // 2:06d}",
            ))
        try:
            pair_jobs = max(1, min(
                4, int(os.environ.get("RQ1_GCOV_PAIR_JOBS", "2")),
            ))
        except (TypeError, ValueError, OverflowError):
            pair_jobs = 2

        def merge_pair(task: tuple[Path, Path, Path]) -> tuple[Path, int, str]:
            left, right, output = task
            if output.exists():
                shutil.rmtree(output, ignore_errors=True)
            code, error = _run([
                merge_tool, "merge", "--output", str(output),
                str(left), str(right),
            ])
            return output, code, error

        with ThreadPoolExecutor(max_workers=min(pair_jobs, len(pair_tasks) or 1)) as pool:
            merged_pairs = [future.result() for future in (
                pool.submit(merge_pair, task) for task in pair_tasks
            )]
        for output, code, error in merged_pairs:
            if code or not output.is_dir():
                return code or 2, error or "gcov-counter-merge-failed", None
            next_roots.append(output)
        if len(level_roots) % 2:
            next_roots.append(level_roots[-1])
        # Intermediate gcov-tool outputs are private staging data.  Keeping
        # every round multiplies the same counters by log2(case_count), which
        # is enough to make a long finalizer exhaust disk/inodes.  Raw case
        # roots are never in generated_roots and remain untouched.
        for old_root in generated_roots:
            if old_root not in next_roots:
                shutil.rmtree(old_root, ignore_errors=True)
        generated_roots = {
            root for root in generated_roots if root in next_roots
        }
        generated_roots.update(output for output, code, _ in merged_pairs if code == 0)
        level_roots = next_roots
        level += 1
    return 0, "", level_roots[0] if level_roots else None


def _gcov_case_roots(profile_dir: Path) -> list[Path]:
    """Find resident per-case raw roots under one Target's staged directory."""
    return sorted(
        path for path in profile_dir.rglob("raw")
        if path.is_dir()
        and (
            path.parent.name.startswith("case-")
            or path.parent.parent.name == "cases"
        )
        and any(path.rglob("*.gcda"))
    )


def _gcov(spec: dict[str, Any], profile: Path, profile_dir: Path) -> tuple[int, str]:
    build_root = _dependency_path(spec.get("build_root")) or Path()
    source_root = _dependency_path(spec.get("source_root")) or Path()
    if not build_root.is_dir() or not source_root.is_dir():
        return 2, "gcov-build-or-source-root-missing"
    names = {source_root.name, *(str(item) for item in spec.get("source_scope", []))}
    for alias_dir in (profile_dir, profile_dir.parent):
        for name in names:
            source_alias = alias_dir / name
            if not source_alias.exists():
                try:
                    source_alias.symlink_to(source_root, target_is_directory=True)
                except FileExistsError:
                    pass
    for name in ("src", "include"):
        source_dir = source_root / name
        source_alias = profile_dir / name
        if source_dir.is_dir() and not source_alias.exists():
            try:
                source_alias.symlink_to(source_dir, target_is_directory=True)
            except FileExistsError:
                pass
    work = Path("/work")
    if work.is_dir():
        for name in names:
            source_alias = work / name
            if not source_alias.exists():
                try:
                    source_alias.symlink_to(source_root, target_is_directory=True)
                except FileExistsError:
                    pass
    # .gcno 记录的是构建容器内的绝对路径（例如 /work/unicorn-8028）；
    # 只按仓库名建别名时 gcovr 找不到源文件，覆盖率会静默变成 unavailable。
    for recorded in _recorded_source_dirs(build_root):
        source_alias = Path(recorded)
        if source_alias.exists():
            continue
        try:
            source_alias.parent.mkdir(parents=True, exist_ok=True)
            source_alias.symlink_to(source_root, target_is_directory=True)
        except (FileExistsError, OSError):
            pass
    # Resident Targets keep one raw directory per case.  Running gcov once
    # per case shard is correct but needlessly slow; merge the counters first
    # and run the collector over the merged tree.  The original case trees
    # remain untouched as the experiment evidence.
    data_root = profile_dir
    gcov_staging: Path | None = None
    case_roots = _gcov_case_roots(profile_dir)
    gcov_merge_tool = shutil.which("gcov-tool")
    if len(case_roots) > 1 and gcov_merge_tool:
        gcov_staging = Path(tempfile.mkdtemp(
            prefix=".rq1-gcov-merge-", dir=str(profile_dir.parent),
        ))
        code, error, current_root = _merge_gcov_case_roots(
            case_roots, gcov_merge_tool, gcov_staging,
        )
        if code or current_root is None:
            shutil.rmtree(gcov_staging, ignore_errors=True)
            return code or 2, error or "gcov-counter-merge-failed"
        data_root = current_root
        for name in names:
            source_alias = data_root / name
            if not source_alias.exists():
                try:
                    source_alias.symlink_to(source_root, target_is_directory=True)
                except FileExistsError:
                    pass

    gcno_files = list(build_root.rglob("*.gcno"))
    by_suffix: dict[tuple[str, ...], list[Path]] = {}
    staged_gcno: dict[Path, Path] = {}
    for gcno in gcno_files:
        relative = gcno.relative_to(build_root)
        destination = data_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(gcno, destination)
        # The dependency checkout can have a fresh mtime even when its Git
        # revision and instrumented binary match this build. GCC 13 rejects
        # that timestamp skew. Refresh only this private staged note; never
        # touch the shared build tree or source checkout.
        os.utime(destination, None)
        staged_gcno[gcno] = destination
        gcda_parts = relative.with_suffix(".gcda").parts
        for length in range(1, len(gcda_parts) + 1):
            by_suffix.setdefault(gcda_parts[-length:], []).append(gcno)
    # gcno 与 gcda 必须同目录才能配对。部分构建（RVVM 的 obj 中间层）会让两者
    # 落在不同层级，此时按文件名在 build_root 里找回并放到 gcda 旁边；
    # 否则 gcov 静默算不出覆盖率。
    by_name: dict[str, list[Path]] = {}
    for item in gcno_files:
        by_name.setdefault(item.name, []).append(item)
    for gcda in (
        path for path in data_root.rglob("*.gcda")
        if not path.name.endswith(".tmp.gcda")
    ):
        if gcda.with_suffix(".gcno").exists():
            continue
        # ``Path.with_suffix`` above checks the destination path, while the
        # lookup table is keyed by the note filename.  Keep the dot in
        # ``foo.gcno``; the old ``foo`` + ``gcno`` spelling silently missed
        # every cross-directory pair and reported valid shards as orphaned.
        matches = by_name.get(gcda.stem + ".gcno", ())
        if len(matches) == 1:
            os.link(staged_gcno[matches[0]], gcda.with_suffix(".gcno"))
            continue
        gcda_parts = gcda.relative_to(data_root).parts
        # ponytail: build a suffix index once; scanning all gcno files for each
        # unmatched gcda is O(gcda × gcno), which dominates large raw batches.
        match = None
        for length in range(1, len(gcda_parts) + 1):
            suffix_matches = tuple(dict.fromkeys(
                by_suffix.get(gcda_parts[-length:], ())
            ))
            if len(suffix_matches) == 1:
                match = suffix_matches[0]
                break
        if match is not None:
            os.link(staged_gcno[match], gcda.with_suffix(".gcno"))
    gcda_inputs = sorted(
        path for path in data_root.rglob("*.gcda")
        if not path.name.endswith(".tmp.gcda")
    )
    if not gcda_inputs:
        if gcov_staging is not None:
            shutil.rmtree(gcov_staging, ignore_errors=True)
        return 2, "gcov-data-missing"
    unpaired = [item for item in gcda_inputs
                if not item.with_suffix(".gcno").is_file()]
    if unpaired:
        labels = [str(item.relative_to(data_root)) for item in unpaired]
        if gcov_staging is not None:
            shutil.rmtree(gcov_staging, ignore_errors=True)
        return 2, "gcov-note-pairing-failed:" + ",".join(labels)
    empty_gcda = [item for item in gcda_inputs if item.stat().st_size == 0]
    gcda = [item for item in gcda_inputs if item.stat().st_size > 0]
    incomplete_flushes = list(profile_dir.rglob(GCOV_FLUSH_INCOMPLETE_MARKER))
    if not gcda:
        if gcov_staging is not None:
            shutil.rmtree(gcov_staging, ignore_errors=True)
        return 2, "gcov-data-empty-only"
    gcovr = shutil.which("gcovr")

    def gcov_json() -> tuple[int, str]:
        """Stream GCC JSON shards when gcovr cannot resolve build-time paths."""
        json_dir = data_root / ".gcov-json"
        json_dir.mkdir(parents=True, exist_ok=True)
        gcda_by_parent: dict[Path, list[Path]] = {}
        for item in gcda:
            gcda_by_parent.setdefault(item.parent, []).append(item)
        accumulator: tuple[dict[tuple[str, int, str], int],
                           dict[tuple[str, int], int],
                           dict[tuple[str, int, int], int]] = ({}, {}, {})
        processed_reports: dict[Path, tuple[int, int, int]] = {}
        gcov = shutil.which(str(_dependency_path(
            spec.get("gcov_tool", "gcov")) or "gcov")) or "gcov"
        for parent, parent_gcda in sorted(gcda_by_parent.items()):
            # Keep argv bounded and consume only new JSON immediately; audit
            # reports stay on disk without being parsed again.
            for offset in range(0, len(parent_gcda), 256):
                code, error = _run([
                    gcov, "-j", "-l", "-b", "-c", "-p", "-x", "-o", str(parent),
                    *map(str, parent_gcda[offset:offset + 256]),
                ], cwd=json_dir)
                if code:
                    return code, error or "gcov-json-command-failed"
                reports = []
                for report in sorted(json_dir.glob("*.gcov.json.gz")):
                    try:
                        stat = report.stat()
                    except OSError:
                        continue
                    signature = (stat.st_ino, stat.st_size, stat.st_mtime_ns)
                    if processed_reports.get(report) == signature:
                        continue
                    processed_reports[report] = signature
                    reports.append(report)
                if reports:
                    code, error = _write_gcov_json_lcov(
                        reports, profile, source_root, accumulator, finalize=False,
                    )
                else:
                    code, error = 0, ""
                # Keep the per-shard JSON beside the merged LCOV profile as
                # auditable raw evidence.  Only new or replaced reports enter
                # the accumulator; retaining old files does not repeat their
                # decompression and JSON parsing.
                if code:
                    return code, error
        code, error = _write_gcov_json_lcov(
            [], profile, source_root, accumulator, finalize=True,
        )
        try:
            json_dir.rmdir()
        except OSError:
            pass
        return code, error

    if gcovr:
        try:
            jobs = int(os.environ.get("RQ1_COVERAGE_JOBS", "2"))
            if jobs <= 0:
                raise ValueError
        except (TypeError, ValueError, OverflowError):
            jobs = 2
        code, error = _run([
            gcovr, "-j", str(max(1, jobs)), "--root", str(source_root),
            "--object-directory", str(data_root), "--gcov-exclude",
            r".*\.tmp\.gcda$", "--lcov", str(profile), str(data_root)],
            cwd=build_root)
        # gcovr 7 may return a non-zero status while writing only an LCOV header
        # when .gcno contains an absolute path from the build container
        # (e.g. /work/libriscv).  The JSON path below remaps that path to the
        # declared source root and keeps coverage available for an unprivileged
        # collector that cannot create /work/libriscv.
        valid = False
        if code == 0 and profile.is_file():
            try:
                content = profile.read_text(encoding="utf-8", errors="replace")
                lines = content.splitlines()
                valid = (any(line.startswith("SF:") for line in lines)
                         and any(line.startswith("DA:") for line in lines))
            except OSError:
                pass
        if not valid:
            code, error = gcov_json()
    else:
        # gcovr is convenient but not a required dependency of the prototype.
        # GCC itself emits enough structured data for the same LCOV summary.
        code, error = gcov_json()
        if code:
            if gcov_staging is not None:
                shutil.rmtree(gcov_staging, ignore_errors=True)
            return code, error
        error = ""
    if code == 0 and profile.is_file():
        root = source_root.resolve()
        lines = []
        for line in profile.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("SF:"):
                try:
                    source = Path(line[3:].strip()).resolve()
                    source.relative_to(root)
                except (OSError, RuntimeError, ValueError):
                    pass
                else:
                    line = f"SF:{source}"
            lines.append(line)
        profile.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if code == 0:
        warnings = []
        if empty_gcda:
            warnings.append(f"gcov-empty-profile-shards-skipped:{len(empty_gcda)}")
        if incomplete_flushes:
            warnings.append(f"gcov-forced-flush-cases:{len(incomplete_flushes)}")
        if warnings:
            error = ";".join(warnings)
    if gcov_staging is not None:
        shutil.rmtree(gcov_staging, ignore_errors=True)
    return code, error


def _llvm(spec: dict[str, Any], profile: Path, profile_dir: Path,
          binary: Path | None) -> tuple[int, str]:
    if not binary or not binary.is_file():
        return 2, "llvm-coverage-binary-missing"
    raw = sorted(profile_dir.rglob("*.profraw"))
    if not raw:
        return 2, "llvm-profraw-missing"
    profdata = profile_dir / "merged.profdata"
    profdata_tool = shutil.which(str(_dependency_path(
        spec.get("profdata_tool", "llvm-profdata")) or "llvm-profdata"))
    cov_tool = shutil.which(str(_dependency_path(
        spec.get("cov_tool", "llvm-cov")) or "llvm-cov"))
    if not profdata_tool or not cov_tool:
        return 127, "llvm-coverage-tools-missing"
    code, merge_error = _run([
        # A deadline-censored RAX process can leave one truncated profraw
        # shard after the completed cases have already flushed valid shards.
        # LLVM can merge the valid inputs while retaining a warning for the
        # invalid one; fail only when every input is invalid.
        profdata_tool, "merge", "--failure-mode=all", "-sparse",
        *map(str, raw), "-o", str(profdata),
    ])
    # ``llvm-profdata --failure-mode=all`` can return non-zero when one shard
    # is truncated while still writing a usable merged profile for the valid
    # shards.  Keep the diagnostic and let llvm-cov export that profile; the
    # caller compares the valid-shard count with expected cases and records
    # the result as partial when necessary.
    if code and (not profdata.is_file() or profdata.stat().st_size == 0):
        return code, merge_error
    if code:
        code = 0
    with profile.open("w", encoding="utf-8") as stream:
        code, export_error = _run(
            [cov_tool, "export", "-format=lcov", f"-instr-profile={profdata}", str(binary)],
            stdout=stream,
        )
    error = "\n".join(
        value for value in (merge_error, export_error) if value
    )
    if code == 0:
        _normalize_llvm_source_paths(
            profile, _dependency_path(spec.get("source_root")) or Path()
        )
    return code, error


def runtime_env(target: dict[str, Any], raw_dir: Path) -> dict[str, str]:
    spec = target.get("source_coverage")
    if not isinstance(spec, dict):
        return {}
    raw_dir.mkdir(parents=True, exist_ok=True)
    collector = str(spec.get("collector", "gcov"))
    if collector in {"gcov", "lcov"}:
        return {"GCOV_PREFIX": str(raw_dir),
                "GCOV_PREFIX_STRIP": str(spec.get("gcov_prefix_strip", 2))}
    if collector == "llvm":
        return {"LLVM_PROFILE_FILE": str(raw_dir / "%m-%p.profraw")}
    return {}


def _normalize_llvm_source_paths(profile: Path, source_root: Path) -> None:
    """Map build-copy ``SF`` paths back to the declared source checkout."""
    if not source_root.is_dir():
        return
    root = source_root.resolve()
    try:
        lines = profile.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return
    changed = False
    normalized: list[str] = []
    for line in lines:
        if not line.startswith("SF:"):
            normalized.append(line)
            continue
        source = Path(line[3:].strip())
        mapped = None
        if source.is_absolute():
            try:
                source.resolve().relative_to(root)
            except (OSError, RuntimeError, ValueError):
                parts = source.parts
                # Rust/LLVM embeds the temporary checkout prefix.  Preserve
                # only a suffix that is an actual file in the declared tree;
                # this also avoids rewriting dependency records wholesale.
                for index, part in enumerate(parts):
                    if part != "src":
                        continue
                    candidate = root.joinpath(*parts[index:])
                    if candidate.is_file():
                        mapped = candidate.resolve()
                        break
        if mapped is not None:
            line = f"SF:{mapped}"
            changed = True
        normalized.append(line)
    if changed:
        profile.write_text("\n".join(normalized) + "\n", encoding="utf-8")


def collect_source_coverage_batch(
    out: Path, target: dict[str, Any], binary: Path | None, raw_dir: Path, *,
    expected_coverage_cases: int | None = None,
    identity_cache: dict[str, dict[str, Any]] | None = None,
    identity_cache_lock: threading.Lock | None = None,
    compute_input_fingerprint: bool = True,
) -> dict[str, Any]:
    """Collect one profile and return its collection evidence.

    ``source_growth`` calls this once per case.  The raw profile is still
    collected and parsed independently, but the binary/source/tool identity is
    static for a staged cell and may be reused through ``identity_cache``.  The
    growth path also disables the input fingerprint because its raw unit sets
    are reduced immediately and the complete fingerprint is recomputed by the
    final offline gate.  The default remains the fully audited path used by
    ordinary collection and aggregation callers.
    """
    started = time.monotonic()
    spec = target.get("source_coverage")
    if not isinstance(spec, dict) or not spec.get("profile"):
        return {"status": "gap", "reason": "source-coverage-not-configured"}
    if not target.get("coverage_binary"):
        return {"status": "gap", "reason": "coverage-binary-not-explicit"}
    if not binary or not binary.is_file():
        return {"status": "gap", "reason": "coverage-binary-missing"}
    profile, profile_dir = _profile(out, spec)
    raw_dir.mkdir(parents=True, exist_ok=True)
    collector = str(spec.get("collector", "gcov"))
    if collector in {"gcov", "lcov"}:
        code, error = _gcov(spec, profile, raw_dir)
    elif collector == "llvm":
        code, error = _llvm(spec, profile, raw_dir, binary)
    elif collector == "dotnet":
        code, error = _dotnet(
            spec, profile, raw_dir, expected_inputs=expected_coverage_cases,
        )
    else:
        code, error = 2, "source-coverage-collector-unsupported"
    # gcov may materialize .gcno beside the raw .gcda files while collecting;
    # fingerprint the post-collection input set so a later finalize can reuse it.
    if compute_input_fingerprint:
        try:
            input_fingerprint = coverage_input_fingerprint(raw_dir, spec)
        except OSError as exc:
            input_fingerprint = None
            code = code or 2
            error = error or str(exc)
    else:
        input_fingerprint = None

    identity = None
    identity_key = None
    if identity_cache is not None:
        try:
            stat = binary.stat() if binary is not None else None
            binary_signature = (
                stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns,
            ) if stat is not None else None
        except OSError:
            binary_signature = None
        identity_key = json.dumps(
            {
                "target_id": target.get("id"),
                # These two paths are deliberately per-case temporary files;
                # they are not part of the immutable provenance identity.
                "spec": {
                    key: value for key, value in spec.items()
                    if key not in {"profile", "identity"}
                },
                "binary": str(binary) if binary is not None else None,
                "binary_signature": binary_signature,
            },
            ensure_ascii=False,
            sort_keys=True,
            default=str,
        )
        if identity_cache_lock is None:
            identity = identity_cache.get(identity_key)
        else:
            with identity_cache_lock:
                identity = identity_cache.get(identity_key)
    if identity is None:
        identity = _identity(target, spec, binary)
        if identity_cache is not None and identity_key is not None:
            if identity_cache_lock is None:
                identity_cache[identity_key] = identity
            else:
                with identity_cache_lock:
                    identity = identity_cache.setdefault(identity_key, identity)
    identity_path = profile_dir / "identity.json"
    identity_path.write_text(json.dumps(identity,
                                        ensure_ascii=False, indent=2) + chr(10),
                             encoding="utf-8")
    try:
        # 这里只确认 collector 产出了非空文件；完整 LCOV 解析由后续
        # target_source_coverage 单遍完成，避免在收尾阶段重复读取大 profile。
        records = False
        if profile.is_file() and code == 0 and profile.stat().st_size > 0:
            with profile.open("r", encoding="utf-8", errors="replace") as stream:
                records = any(line.startswith(("FN:", "FNDA:", "DA:", "BRDA:"))
                               for line in stream)
    except OSError:
        records = False
    if code == 0 and not records:
        error = error or "source-coverage-records-missing"
    source_commit_mismatch = _source_commit_proven_mismatch(identity)
    if collector == "dotnet" and code == 0 and isinstance(error, str):
        collector_warnings = [item for item in error.split(";") if item]
    elif collector == "llvm" and code == 0 and isinstance(error, str):
        collector_warnings = [
            item.strip() for item in error.splitlines()
            if item.strip().lower().startswith("warning:")
        ]
    elif collector in {"gcov", "lcov"} and code == 0 and isinstance(error, str):
        collector_warnings = [
            item for item in error.split(";")
            if item.startswith(("gcov-empty-profile-shards-skipped:",
                                "gcov-forced-flush-cases:"))
        ]
    else:
        collector_warnings = []
    invalid_llvm_profiles = sum(
        "invalid instrumentation profile data" in item
        for item in collector_warnings
    ) if collector == "llvm" else 0
    partial_reason = next(
        (item for item in collector_warnings
         if item.startswith("dotnet-cobertura-inputs-skipped:")),
        None,
    )
    if collector in {"gcov", "lcov"}:
        partial_reason = ";".join(collector_warnings) or None
    if collector == "llvm" and collector_warnings:
        # llvm-cov 23 reports this for Rust generated/uninstantiated
        # function records even when it emits a complete LCOV profile with
        # exit status 0. Keep the diagnostic for auditability, but do not
        # turn valid coverage into a partial result.
        if not all(_LLVM_KNOWN_NONFATAL_WARNING_RE.fullmatch(item)
                   for item in collector_warnings):
            partial_reason = "source-coverage-collector-warning"
        elif invalid_llvm_profiles:
            valid_llvm_profiles = max(
                0, len(list(raw_dir.rglob("*.profraw"))) - invalid_llvm_profiles,
            )
            if expected_coverage_cases is None:
                partial_reason = "source-coverage-collector-warning"
            elif valid_llvm_profiles < expected_coverage_cases:
                partial_reason = "llvm-profraw-count-mismatch"
    status = "partial" if records and code == 0 \
        and not source_commit_mismatch \
        and identity["coverage_binary_sha256_match"] \
        and identity["instrumented_binaries_match"] \
        and partial_reason else "observed" if records and code == 0 \
        and not source_commit_mismatch \
        and identity["coverage_binary_sha256_match"] \
        and identity["instrumented_binaries_match"] \
        else "gap" if records else "unavailable"
    reason = partial_reason if status == "partial" else None if status == "observed" else (
        (None if records and code == 0 else error or None)
        or _identity_gap_reason(identity)
    )
    provenance_warnings = _identity_provenance_warnings(identity)
    return {"status": status, "collector": collector,
            "profile": _run_artifact_ref(out, profile),
            "identity": _run_artifact_ref(out, identity_path),
            "raw_dir": _run_artifact_ref(out, raw_dir), "returncode": code,
            "coverage_binary": identity.get("coverage_binary"),
            **_identity_summary(identity),
            "provenance_warning": provenance_warnings[0] if provenance_warnings else None,
            "provenance_warnings": provenance_warnings,
            "warnings": collector_warnings,
            "input_fingerprint": input_fingerprint,
            # 采集器成功时的 stderr 只保留为 warnings；真正影响准入的
            # 收集缺口仍由 returncode、profile 和身份字段判定。
            "reason": _error_summary(reason),
            "elapsed_s": round(time.monotonic() - started, 6)}
