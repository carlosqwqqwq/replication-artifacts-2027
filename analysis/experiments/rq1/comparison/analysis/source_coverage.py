_DEFAULT_COVERAGE_COMMAND_TIMEOUT_SECONDS = 600


def _coverage_command_timeout() -> int:
    """Keep one collector command from holding the run finalizer forever."""
    try:
        value = int(os.environ.get(
            "RQ1_COVERAGE_COMMAND_TIMEOUT_SECONDS",
            str(_DEFAULT_COVERAGE_COMMAND_TIMEOUT_SECONDS),
        ))
    except (TypeError, ValueError, OverflowError):
        value = _DEFAULT_COVERAGE_COMMAND_TIMEOUT_SECONDS
    return max(1, value)


def _hit_count(value: object) -> int:
    """Parse an LCOV execution count without truncating malformed values."""
    if isinstance(value, bool) or value is None:
        raise ValueError("coverage count must be a non-negative integer")
    # Parse integer inputs and digit-only strings before converting to float;
    # otherwise large counters lose precision at the IEEE-754 boundary.
    if type(value) is int:
        parsed = value
    elif isinstance(value, str) and re.fullmatch(r"[+-]?\d+", value.strip()):
        parsed = int(value.strip(), 10)
    else:
        try:
            parsed_float = float(value)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError("coverage count must be a non-negative integer") from exc
        if not math.isfinite(parsed_float) or parsed_float < 0 or not parsed_float.is_integer():
            raise ValueError("coverage count must be a non-negative integer")
        parsed = int(parsed_float)
    if parsed < 0:
        raise ValueError("coverage count must be a non-negative integer")
    return parsed


def _safe_count(value: object, default: int = 0) -> int:
    try:
        return _hit_count(default if value is None else value)
    except ValueError:
        return default


def _dependency_path(value: object) -> Path | None:
    """Resolve container dependency and run paths when collecting on the host."""
    if not isinstance(value, (str, Path)) or not str(value):
        return None
    path = Path(value)
    if not path.is_absolute():
        return path
    run_root_value = os.environ.get("RQ1_RUN_ROOT")
    if run_root_value:
        run_root = Path(run_root_value)
        prefix = Path("/opt/runs") / run_root.name
        try:
            return run_root / path.relative_to(prefix)
        except ValueError:
            pass
    try:
        relative = path.relative_to("/path/to/deps")
    except ValueError:
        return path
    return Path(os.environ.get("RQ1_DEPS", "/path/to/deps")) / relative


def _generated_untracked(code: str, path: str, source_root: Path | None = None) -> bool:
    if code != "??":
        return False
    relative = Path(path.split(" -> ")[-1])
    if relative.name.endswith(".profraw"):
        return True
    if relative == Path("Cargo.lock.git-source") and source_root is not None:
        try:
            with (source_root / relative).open(encoding="utf-8") as stream:
                return stream.readline().rstrip("\r\n") == (
                    "# This file is automatically @generated by Cargo."
                )
        except (OSError, UnicodeError):
            return False
    return False


def _git_attestation(path: object) -> dict[str, Any]:
    if not isinstance(path, str) or not path:
        return {"head": None, "status": "unavailable", "source_dirty": False,
                "dirty_path_count": 0, "non_generated_dirty_paths": [],
                "generated_untracked_path_count": 0}
    try:
        result = subprocess.run(
            ["git", "-C", path, "rev-parse", "HEAD"],
            capture_output=True, text=True, check=False, timeout=10,
        )
        if result.returncode != 0:
            return {"head": None, "status": "unavailable", "source_dirty": False,
                    "dirty_path_count": 0, "non_generated_dirty_paths": [],
                    "generated_untracked_path_count": 0}
        clean = subprocess.run(
            ["git", "-C", path, "status", "--porcelain", "--untracked-files=all"],
            capture_output=True, text=True, check=False, timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return {"head": None, "status": "unavailable", "source_dirty": False,
                "dirty_path_count": 0, "non_generated_dirty_paths": [],
                "generated_untracked_path_count": 0}
    if clean.returncode != 0:
        return {"head": None, "status": "unavailable", "source_dirty": False,
                "dirty_path_count": 0, "non_generated_dirty_paths": [],
                "generated_untracked_path_count": 0}
    entries = [(line[:2], line[3:]) for line in clean.stdout.splitlines() if len(line) >= 4]
    source_root = Path(path)
    generated = [
        entry_path for code, entry_path in entries
        if _generated_untracked(code, entry_path, source_root)
    ]
    generated_paths = set(generated)
    non_generated = [
        entry_path for code, entry_path in entries
        if not (code == "??" and entry_path in generated_paths)
    ]
    head = result.stdout.strip() or None
    source_dirty = bool(non_generated)
    return {
        "head": head,
        "status": "clean" if head and not source_dirty else "dirty" if head else "unavailable",
        "source_dirty": source_dirty,
        "dirty_path_count": len(entries),
        "non_generated_dirty_paths": non_generated[:20],
        "generated_untracked_path_count": len(generated),
    }


def _git_state(path: object) -> tuple[str | None, bool]:
    """Backward-compatible compact view used by lightweight collectors/tests."""
    state = _git_attestation(path)
    return state["head"], state["source_dirty"]


def _manifest_source_identity(spec: dict[str, Any]) -> dict[str, Any] | None:
    run_root = os.environ.get("RQ1_RUN")
    if not run_root:
        return None
    try:
        manifest = json.loads(
            (Path(run_root) / "execution-manifest.json").read_text(encoding="utf-8")
        )
    except (OSError, TypeError, ValueError):
        return None
    if not isinstance(manifest, dict):
        return None
    source_root = spec.get("source_root")
    identities = manifest.get("coverage_source_identities", [])
    if not isinstance(identities, (list, tuple)):
        return None
    for item in identities:
        if isinstance(item, dict) and item.get("source_root") == source_root:
            return item
    return None


def _run(argv: list[str], *, stdout=None, cwd: Path | None = None,
         env: dict[str, str] | None = None) -> tuple[int, str]:
    try:
        # 覆盖工具（尤其 reportgenerator）可能把每个缺失 source path 的
        # warning 写到 stdout；默认捕获在内存中，只有命令失败时才并入错误证据，
        # 不把 warning 混入 profile。需要 profile 的调用方显式传入文件句柄。
        capture_stdout = stdout is None
        output = subprocess.PIPE if capture_stdout else stdout
        result = subprocess.run(argv, stdout=output, stderr=subprocess.PIPE, cwd=cwd,
                                env=env, text=True, check=False,
                                timeout=_coverage_command_timeout())
    except subprocess.TimeoutExpired:
        command = Path(str(argv[0])).name if argv else "unknown"
        return 124, f"coverage-command-timeout:{command}"
    except OSError as exc:
        return 127, str(exc)
    error = result.stderr or ""
    if capture_stdout and result.returncode != 0 and result.stdout:
        error = f"{error}\nstdout:\n{result.stdout}" if error else result.stdout
    return result.returncode, error


def _error_summary(error: str | None) -> str | None:
    if not error or not error.strip():
        return None
    lines = [line.strip() for line in error.splitlines() if line.strip()]
    message = next(
        (line for line in lines if "Cannot open JSON output file" in line),
        lines[0] if lines else "coverage-collector-failed",
    )
    return message if len(message) <= 240 else message[:237] + "..."


def _file_sha256(path: Path | None) -> str | None:
    if path is None or not path.is_file():
        return None
    try:
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(1 << 20), b""):
                digest.update(block)
        return digest.hexdigest()
    except OSError:
        return None


def _profile(out: Path, spec: dict[str, Any]) -> tuple[Path, Path]:
    value = _dependency_path(spec["profile"]) or Path(str(spec["profile"]))
    profile = value if value.is_absolute() else out / value
    profile.parent.mkdir(parents=True, exist_ok=True)
    return profile, profile.parent


def _run_artifact_ref(out: Path, path: Path | None) -> str | None:
    """Store run-owned coverage artifacts as paths relative to the run root."""
    if path is None:
        return None
    try:
        return str(path.resolve().relative_to(out.resolve()))
    except (OSError, ValueError):
        return str(path)


def _collector_tools(spec: dict[str, Any], collector: str) -> dict[str, str]:
    if collector == "dotnet":
        requested = {
            "dotnet_coverage": str(_dependency_path(spec.get("launcher")))
            if spec.get("launcher") else shutil.which("dotnet-coverage"),
            "reportgenerator": str(_dependency_path(spec.get("reportgenerator")))
            if spec.get("reportgenerator") else shutil.which("reportgenerator"),
        }
    elif collector == "llvm":
        requested = {
            "llvm_profdata": str(_dependency_path(spec.get("profdata_tool")))
            if spec.get("profdata_tool") else shutil.which("llvm-profdata"),
            "llvm_cov": str(_dependency_path(spec.get("cov_tool")))
            if spec.get("cov_tool") else shutil.which("llvm-cov"),
        }
    else:
        requested = {
            "gcovr": shutil.which("gcovr"),
            "gcov": shutil.which(str(_dependency_path(
                spec.get("gcov_tool", "gcov")) or "gcov")),
        }
    tools = {}
    for name, value in requested.items():
        if not isinstance(value, str) or not value:
            tools[name] = "missing"
            continue
        path = Path(value)
        if not path.is_file():
            tools[name] = f"unreadable:{value}"
            continue
        digest = _file_sha256(path)
        if digest is None:
            raise OSError(f"coverage-tool-unreadable:{path}")
        tools[name] = f"{path.resolve()}:{digest}"
    return tools


def instrumented_binary_identity(spec: dict[str, Any]) -> list[dict[str, Any]]:
    """Hash every additional binary that produces this source profile."""
    declared = spec.get("instrumented_binaries", [])
    if not isinstance(declared, list):
        return [{"reason": "instrumented-binaries-not-a-list",
                 "sha256_match": False}]
    deps_root = Path(os.environ.get("RQ1_DEPS", "/path/to/deps"))
    identities = []
    for item in declared:
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            identities.append({"reason": "instrumented-binary-path-missing",
                               "sha256_match": False})
            continue
        requested = Path(item["path"])
        path = requested if requested.is_absolute() else deps_root / requested
        observed = _file_sha256(path)
        expected = item.get("expected_sha256")
        match = bool(isinstance(expected, str) and observed
                     and expected.lower() == observed)
        identities.append({
            "path": str(path.resolve()),
            "expected_sha256": expected,
            "sha256": observed,
            "sha256_match": match,
        })
    return identities


def coverage_input_files(raw_dir: Path, collector: object) -> list[Path]:
    """List raw inputs once so collection, reuse, and reporting count agree."""
    collector = str(collector or "gcov")
    if collector == "dotnet":
        paths = [
            *raw_dir.rglob("*.coverage"),
            *raw_dir.rglob("*.cobertura.xml"),
            *raw_dir.rglob("*.cobertura.xml.gz"),
        ]
        return sorted({path for path in paths if (
            path.name not in {"merged.cobertura.xml", "merged.cobertura.xml.gz"}
            and not any(part.startswith(".reportgenerator-staging-")
                        for part in path.relative_to(raw_dir).parts)
        )})
    if collector == "llvm":
        return sorted(raw_dir.rglob("*.profraw"))
    paths = {
        path for pattern in ("*.gcda", "*.gcno", "*.info", "*.gcov")
        for path in raw_dir.rglob(pattern)
        # Some external generators leave a scratch counter beside the real
        # gcov shard (for example ``last_variant_txt.tmp.gcda``).  It is not
        # produced by an instrumented object and has no matching .gcno; keep
        # it out of the collector denominator and fingerprint.
        if not path.name.endswith((".tmp.gcda", ".tmp.gcno"))
    }
    paths.update(raw_dir.rglob(GCOV_FLUSH_INCOMPLETE_MARKER))
    return sorted(paths)


def coverage_input_fingerprint(raw_dir: Path, spec: dict[str, Any]) -> str:
    """Return a content identity for every raw coverage input.

    A size/mtime tuple can stay unchanged when a coverage shard is replaced in
    place.  Reuse is a correctness decision, so every discovered input is hashed
    and an unreadable input is reported to the caller instead of being skipped.
    """
    collector = str(spec.get("collector", "gcov"))
    paths = coverage_input_files(raw_dir, collector)
    entries = []
    for path in paths:
        digest = _file_sha256(path)
        if digest is None:
            raise OSError(f"coverage-input-unreadable:{path}")
        entries.append((str(path.relative_to(raw_dir)), digest))
    payload = json.dumps(
        {"fingerprint_version": SOURCE_COVERAGE_PIPELINE,
         "collector": collector, "spec": spec,
         "collector_tools": _collector_tools(spec, collector),
         "instrumented_binaries": instrumented_binary_identity(spec),
         "files": entries},
        ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str,
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def compress_dotnet_report(path: Path) -> Path:
    """Compress one completed Cobertura artifact in place, atomically."""
    if not path.is_file() or not path.name.endswith(".cobertura.xml"):
        return path
    compressed = Path(str(path) + ".gz")
    temporary = compressed.with_name(compressed.name + ".tmp")
    try:
        with path.open("rb") as source, temporary.open("wb") as output:
            with gzip.GzipFile(fileobj=output, mode="wb", filename="",
                               compresslevel=1, mtime=0) as stream:
                shutil.copyfileobj(source, stream, length=1 << 20)
        os.replace(temporary, compressed)
        path.unlink()
    except OSError:
        try:
            temporary.unlink(missing_ok=True)
        except OSError:
            pass
        raise
    return compressed


def _cobertura_input_error(path: Path) -> str | None:
    """Validate one Cobertura document while keeping XML memory bounded."""
    parser = ET.XMLPullParser(events=("start", "end"))
    root_has_branches = None
    try:
        with path.open("rb") as stream:
            while block := stream.read(1 << 16):
                parser.feed(block)
                for event, element in parser.read_events():
                    if event == "start" and root_has_branches is None:
                        if element.tag.rsplit("}", 1)[-1] != "coverage":
                            return "dotnet-cobertura-input-invalid"
                        try:
                            root_has_branches = int(
                                element.attrib.get("branches-valid", "0")) > 0
                        except ValueError:
                            return "dotnet-cobertura-input-invalid"
                    elif event == "end":
                        element.clear()
        parser.close()
    except (OSError, ET.ParseError, ValueError):
        return "dotnet-cobertura-input-invalid"
    if root_has_branches is None:
        return "dotnet-cobertura-input-invalid"
    return None if root_has_branches else "dotnet-cobertura-branch-metadata-missing"


def _cobertura_has_branch_metadata(path: Path) -> bool:
    """Compatibility predicate for callers that only need a boolean check."""
    return _cobertura_input_error(path) is None


def _dotnet(
    spec: dict[str, Any], profile: Path, raw_dir: Path, *,
    expected_inputs: int | None = None,
) -> tuple[int, str]:
    """Convert every per-execution Cobertura report together to stable LCOV."""
    inputs = coverage_input_files(raw_dir, "dotnet")
    coverage_files = [path for path in inputs if path.suffix == ".coverage"]
    reports = [path for path in inputs if path.name.endswith(
        (".cobertura.xml", ".cobertura.xml.gz"))]
    if coverage_files and reports:
        return 2, "dotnet-coverage-input-format-mixed"
    if coverage_files:
        return 2, "dotnet-native-coverage-branch-data-unavailable"
    if not reports:
        return 2, "dotnet-coverage-data-missing"
    if spec.get("collector_input_format") != "cobertura":
        return 2, "dotnet-coverage-input-format-not-declared"

    launcher = str(_dependency_path(spec.get("launcher"))) \
        if spec.get("launcher") else shutil.which("dotnet-coverage")
    reportgenerator = str(_dependency_path(spec.get("reportgenerator"))) \
        if spec.get("reportgenerator") else shutil.which("reportgenerator")
    if not launcher or not reportgenerator:
        return 127, "dotnet-coverage-tools-missing"

    env = dict(os.environ)
    dotnet_root = env.get("RQ1_DOTNET_RUNTIME")
    if dotnet_root:
        env["DOTNET_ROOT"] = dotnet_root
        env["PATH"] = dotnet_root + os.pathsep + env.get("PATH", "")

    try:
        input_fingerprint = coverage_input_fingerprint(raw_dir, spec)
    except OSError as exc:
        return 2, str(exc)
    shard_dir = raw_dir / ".report-shards" / f"cobertura-{input_fingerprint}"
    generated = shard_dir / "lcov.info"
    marker = shard_dir / "complete.json"
    cached = False
    skipped_reasons: list[str] = []
    input_warnings: list[str] = []
    try:
        cached_metadata = json.loads(marker.read_text(encoding="utf-8"))
        cached = (
            isinstance(cached_metadata, dict)
            and generated.is_file() and generated.stat().st_size > 0
            and cached_metadata.get("input_fingerprint") == input_fingerprint
            and cached_metadata.get("profile_sha256") == _file_sha256(generated)
        )
        if cached and isinstance(cached_metadata.get("skipped_reasons"), list):
            skipped_reasons = [str(item) for item in cached_metadata["skipped_reasons"]
                               if str(item)]
        if cached and isinstance(cached_metadata.get("warnings"), list):
            input_warnings = [str(item) for item in cached_metadata["warnings"]
                              if str(item)]
    except (OSError, TypeError, ValueError):
        pass
    if not cached:
        try:
            chunk_size = max(1, int(os.environ.get("RQ1_DOTNET_REPORT_CHUNK", "16")))
        except (TypeError, ValueError, OverflowError):
            chunk_size = 16
        if len(reports) > chunk_size:
            return _dotnet_chunked(
                spec, profile, raw_dir, reports, reportgenerator,
                expected_inputs=expected_inputs, shard_dir=shard_dir,
                generated=generated, marker=marker,
                input_fingerprint=input_fingerprint,
                chunk_size=chunk_size, env=env,
            )
        generated.parent.mkdir(parents=True, exist_ok=True)
        try:
            generated.unlink(missing_ok=True)
            marker.unlink(missing_ok=True)
        except OSError:
            return 2, "dotnet-coverage-cache-unavailable"
        try:
            with tempfile.TemporaryDirectory(
                    prefix=f".reportgenerator-staging-{input_fingerprint[:12]}-",
                    dir=raw_dir) as temporary_dir:
                staging = Path(temporary_dir)
                usable_reports = []
                for index, report in enumerate(reports):
                    staged = staging / f"{index:08d}.cobertura.xml"
                    if report.name.endswith(".gz"):
                        try:
                            with gzip.open(report, "rb") as source, staged.open("wb") as dest:
                                shutil.copyfileobj(source, dest, length=1 << 20)
                        except (OSError, EOFError, zlib.error) as exc:
                            # A timed-out execution can leave one truncated
                            # gzip next to complete reports.  One bad shard
                            # must not discard the valid shards that still
                            # contain simulator line/function data.
                            skipped_reasons.append(
                                f"dotnet-cobertura-input-unreadable:{type(exc).__name__}"
                            )
                            staged.unlink(missing_ok=True)
                            continue
                    else:
                        try:
                            staged.symlink_to(report.resolve(strict=True))
                        except OSError:
                            try:
                                shutil.copyfile(report, staged)
                            except OSError as exc:
                                skipped_reasons.append(
                                    f"dotnet-cobertura-input-unreadable:{type(exc).__name__}"
                                )
                                staged.unlink(missing_ok=True)
                                continue
                    input_error = _cobertura_input_error(staged)
                    if input_error == "dotnet-cobertura-branch-metadata-missing":
                        # Branch metadata is optional for this collector.  Keep
                        # the report so reportgenerator can still emit function
                        # and line records; the source summary will mark branch
                        # coverage as unavailable/partial.
                        input_warnings.append(input_error)
                    elif input_error:
                        skipped_reasons.append(input_error)
                        staged.unlink(missing_ok=True)
                        continue
                    usable_reports.append(staged)

                if (
                    expected_inputs is not None
                    and expected_inputs > 0
                    and len(usable_reports) >= expected_inputs
                    and skipped_reasons
                ):
                    input_warnings.append(
                        f"dotnet-cobertura-extra-inputs-skipped:{len(skipped_reasons)}:"
                        + ",".join(sorted(set(skipped_reasons)))
                    )
                    skipped_reasons.clear()
                if not usable_reports:
                    return 2, skipped_reasons[0] if skipped_reasons else (
                        "dotnet-cobertura-inputs-missing"
                    )

                code, error = _run(
                    [str(reportgenerator),
                     f"-reports:{staging / '*.cobertura.xml'}",
                     f"-targetdir:{shard_dir}", "-reporttypes:lcov"],
                    env=env,
                )
                if code or not generated.is_file() or generated.stat().st_size == 0:
                    try:
                        generated.unlink(missing_ok=True)
                    except OSError:
                        pass
                    return code or 2, error or "reportgenerator-lcov-output-missing"
                try:
                    saw_source = saw_function = saw_line = saw_branch = False
                    with generated.open("r", encoding="utf-8", errors="replace") as stream:
                        for line in stream:
                            saw_source |= line.startswith("SF:")
                            saw_function |= line.startswith(("FN:", "FNDA:"))
                            saw_line |= line.startswith("DA:")
                            saw_branch |= line.startswith("BRDA:")
                            if saw_source and saw_line and saw_branch:
                                break
                    if not (saw_source and (saw_function or saw_line)):
                        generated.unlink(missing_ok=True)
                        return 2, "reportgenerator-lcov-function-line-records-missing"
                    if not saw_branch:
                        input_warnings.append("reportgenerator-lcov-branch-records-missing")
                except OSError as exc:
                    return 2, f"reportgenerator-lcov-output-unreadable:{type(exc).__name__}"
        except OSError as exc:
            return 2, f"dotnet-cobertura-staging-failed:{type(exc).__name__}"
        try:
            marker_tmp = marker.with_name(marker.name + ".tmp")
            marker_tmp.write_text(json.dumps({
                "input_fingerprint": input_fingerprint,
                "profile_sha256": _file_sha256(generated),
                "skipped_reasons": sorted(set(skipped_reasons)),
                "warnings": sorted(set(input_warnings)),
            }, sort_keys=True) + "\n", encoding="utf-8")
            os.replace(marker_tmp, marker)
        except OSError as exc:
            return 2, f"dotnet-coverage-cache-marker-failed:{type(exc).__name__}"

    if (
        cached
        and expected_inputs is not None
        and expected_inputs > 0
        and skipped_reasons
        and len(reports) - len(skipped_reasons) >= expected_inputs
    ):
        input_warnings.append(
            f"dotnet-cobertura-extra-inputs-skipped:{len(skipped_reasons)}:"
            + ",".join(sorted(set(skipped_reasons)))
        )
        skipped_reasons.clear()

    try:
        profile.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(generated, profile)
    except OSError as exc:
        return 2, f"dotnet-lcov-profile-copy-failed:{type(exc).__name__}"
    warnings = []
    if skipped_reasons:
        warnings.append(
            f"dotnet-cobertura-inputs-skipped:{len(skipped_reasons)}:"
            + ",".join(sorted(set(skipped_reasons)))
        )
    warnings.extend(sorted(set(input_warnings)))
    warning = ";".join(warnings)
    return 0, warning


def _dotnet_chunked(
    spec: dict[str, Any], profile: Path, raw_dir: Path,
    reports: list[Path], reportgenerator: str, *, expected_inputs: int | None,
    shard_dir: Path, generated: Path, marker: Path, input_fingerprint: str,
    chunk_size: int, env: dict[str, str],
) -> tuple[int, str]:
    """Process large Cobertura batches in bounded ReportGenerator chunks.

    A Renode report is roughly 70 MiB after decompression.  Feeding hundreds
    of reports to one ReportGenerator process can exceed its memory envelope;
    chunking keeps the collector bounded and merges only compact LCOV shards.
    """
    generated.parent.mkdir(parents=True, exist_ok=True)
    try:
        generated.unlink(missing_ok=True)
        marker.unlink(missing_ok=True)
    except OSError:
        return 2, "dotnet-coverage-cache-unavailable"
    shard_dir.mkdir(parents=True, exist_ok=True)

    def has_records(path: Path) -> tuple[bool, bool]:
        saw_source = saw_function = saw_line = saw_branch = False
        try:
            with path.open("r", encoding="utf-8", errors="replace") as stream:
                for line in stream:
                    saw_source |= line.startswith("SF:")
                    saw_function |= line.startswith(("FN:", "FNDA:"))
                    saw_line |= line.startswith("DA:")
                    saw_branch |= line.startswith("BRDA:")
                    if saw_source and (saw_function or saw_line) and saw_branch:
                        break
        except OSError:
            return False, False
        return saw_source and (saw_function or saw_line), saw_branch

    chunks = [
        (chunk_index // chunk_size, reports[chunk_index:chunk_index + chunk_size])
        for chunk_index in range(0, len(reports), chunk_size)
    ]

    def collect_chunk(
        chunk_index: int, chunk: list[Path],
    ) -> tuple[int, Path | None, list[str], list[str], int, str]:
        skipped_reasons: list[str] = []
        input_warnings: list[str] = []
        try:
            with tempfile.TemporaryDirectory(
                    prefix=f".reportgenerator-staging-{input_fingerprint[:12]}-",
                    dir=raw_dir) as temporary_dir:
                staging = Path(temporary_dir)
                usable_reports: list[Path] = []
                for index, report in enumerate(chunk):
                    staged = staging / f"{index:08d}.cobertura.xml"
                    try:
                        if report.name.endswith(".gz"):
                            with gzip.open(report, "rb") as source, staged.open("wb") as dest:
                                shutil.copyfileobj(source, dest, length=1 << 20)
                        else:
                            staged.symlink_to(report.resolve(strict=True))
                    except (OSError, EOFError, zlib.error) as exc:
                        skipped_reasons.append(
                            f"dotnet-cobertura-input-unreadable:{type(exc).__name__}"
                        )
                        staged.unlink(missing_ok=True)
                        continue
                    input_error = _cobertura_input_error(staged) \
                        if validate_inputs else None
                    if input_error == "dotnet-cobertura-branch-metadata-missing":
                        input_warnings.append(input_error)
                    elif input_error:
                        skipped_reasons.append(input_error)
                        staged.unlink(missing_ok=True)
                        continue
                    usable_reports.append(staged)
                if not usable_reports:
                    return chunk_index, None, skipped_reasons, input_warnings, 0, ""
                target_dir = shard_dir / f"chunk-{chunk_index:04d}"
                if target_dir.exists():
                    shutil.rmtree(target_dir)
                code, error = _run(
                    [str(reportgenerator),
                     f"-reports:{staging / '*.cobertura.xml'}",
                     f"-targetdir:{target_dir}", "-reporttypes:lcov"],
                    env=env,
                )
                shard = target_dir / "lcov.info"
                valid, has_branch = (
                    has_records(shard) if code == 0 and shard.is_file() else (False, False)
                )
                if code or not valid:
                    return (
                        chunk_index, None, skipped_reasons, input_warnings,
                        code or 2, error or "reportgenerator-lcov-function-line-records-missing",
                    )
                if not has_branch:
                    input_warnings.append("reportgenerator-lcov-branch-records-missing")
                return chunk_index, shard, skipped_reasons, input_warnings, 0, ""
        except OSError as exc:
            return (
                chunk_index, None, skipped_reasons, input_warnings, 2,
                f"dotnet-cobertura-staging-failed:{type(exc).__name__}",
            )

    try:
        chunk_jobs = max(1, min(
            len(chunks), int(os.environ.get("RQ1_DOTNET_CHUNK_JOBS", "1")),
        ))
    except (TypeError, ValueError, OverflowError):
        chunk_jobs = 1
    validate_inputs = str(
        os.environ.get("RQ1_DOTNET_VALIDATE_INPUTS", "1")
    ).strip().lower() not in {"0", "false", "no", "off"}
    results = []
    with ThreadPoolExecutor(max_workers=chunk_jobs) as pool:
        futures = [pool.submit(collect_chunk, index, chunk) for index, chunk in chunks]
        for future in as_completed(futures):
            results.append(future.result())
    results.sort(key=lambda item: item[0])
    shard_profiles: list[Path] = []
    skipped_reasons: list[str] = []
    input_warnings: list[str] = []
    for _index, shard, skipped, warnings, code, error in results:
        skipped_reasons.extend(skipped)
        input_warnings.extend(warnings)
        if code:
            return code, error or "reportgenerator-lcov-output-missing"
        if shard is not None:
            shard_profiles.append(shard)

    if not shard_profiles:
        return 2, skipped_reasons[0] if skipped_reasons else (
            "dotnet-cobertura-inputs-missing"
        )
    code, error = _merge_lcov_profiles(shard_profiles, generated)
    if code or not generated.is_file() or generated.stat().st_size == 0:
        return code or 2, error or "reportgenerator-lcov-output-missing"
    try:
        marker_tmp = marker.with_name(marker.name + ".tmp")
        marker_tmp.write_text(json.dumps({
            "input_fingerprint": input_fingerprint,
            "profile_sha256": _file_sha256(generated),
            "skipped_reasons": sorted(set(skipped_reasons)),
            "warnings": sorted(set(input_warnings)),
        }, sort_keys=True) + "\n", encoding="utf-8")
        os.replace(marker_tmp, marker)
    except OSError as exc:
        return 2, f"dotnet-coverage-cache-marker-failed:{type(exc).__name__}"
    try:
        profile.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(generated, profile)
    except OSError as exc:
        return 2, f"dotnet-lcov-profile-copy-failed:{type(exc).__name__}"
    warnings = []
    if skipped_reasons:
        warnings.append(
            f"dotnet-cobertura-inputs-skipped:{len(skipped_reasons)}:"
            + ",".join(sorted(set(skipped_reasons)))
        )
    warnings.extend(sorted(set(input_warnings)))
    return 0, ";".join(warnings)


def _merge_lcov_profiles(profiles: list[Path], profile: Path) -> tuple[int, str]:
    """Merge already compact LCOV shards using the same max-hit semantics."""
    # Function names are not unique within a source file (C# overloads and
    # generated accessors are common).  Keep the declaration line in the key
    # and pair FNDA records in declaration order so merging cannot collapse a
    # covered overload into its sibling.
    functions: dict[tuple[str, str, str], int] = {}
    lines: dict[tuple[str, str], int] = {}
    branches: dict[tuple[str, str], int] = {}
    # ponytail: index by source while parsing; filtering the global maps once
    # per source made a large LCOV union quadratic in the record count.
    functions_by_source: dict[str, list[tuple[str, str, str]]] = {}
    lines_by_source: dict[str, list[tuple[str, str]]] = {}
    branches_by_source: dict[str, list[tuple[str, str]]] = {}
    source = None
    try:
        for shard in profiles:
            source = None
            record_open = False
            function_keys: dict[str, list[tuple[str, str, str]]] = {}
            function_cursor: dict[str, int] = {}
            open_profile = gzip.open if shard.suffix == ".gz" else Path.open
            with open_profile(shard, "rt", encoding="utf-8", errors="replace") as stream:
                for raw in stream:
                    raw = raw.rstrip("\r\n")
                    if raw.startswith("SF:"):
                        if record_open:
                            return 2, "lcov-merge-profile-truncated"
                        source = raw[3:].strip()
                        record_open = True
                    elif raw == "end_of_record":
                        if not record_open:
                            return 2, "lcov-merge-profile-invalid"
                        source = None
                        record_open = False
                        function_keys = {}
                        function_cursor = {}
                    elif not record_open or not source:
                        continue
                    elif raw.startswith("FN:"):
                        line, name = raw[3:].split(",", 1)
                        key = (source, line, name)
                        function_keys.setdefault(name, []).append(key)
                        # FN is the function denominator even when a malformed
                        # shard omitted its FNDA line; retain it as uncovered.
                        if key not in functions:
                            functions[key] = 0
                            functions_by_source.setdefault(source, []).append(key)
                    elif raw.startswith("FNDA:"):
                        count, name = raw[5:].split(",", 1)
                        candidates = function_keys.get(name, [])
                        cursor = function_cursor.get(name, 0)
                        if cursor < len(candidates):
                            key = candidates[cursor]
                            function_cursor[name] = cursor + 1
                        else:
                            # Preserve an FNDA-only record rather than losing
                            # its numerator during the merge.
                            key = (source, "0", name)
                            if key not in functions:
                                functions_by_source.setdefault(source, []).append(key)
                        functions[key] = max(functions.get(key, 0), _hit_count(count))
                    elif raw.startswith("DA:"):
                        line, count, *_ = raw[3:].split(",")
                        key = (source, line)
                        if key not in lines:
                            lines_by_source.setdefault(source, []).append(key)
                        lines[key] = max(lines.get(key, 0), _hit_count(count))
                    elif raw.startswith("BRDA:"):
                        line, block, branch, taken = raw[5:].split(",", 3)
                        key = (source, f"{line},{block},{branch}")
                        if key not in branches:
                            branches_by_source.setdefault(source, []).append(key)
                        branches[key] = max(
                            branches.get(key, 0), 0 if taken == "-" else _hit_count(taken))
            if record_open:
                return 2, "lcov-merge-profile-truncated"
    except (OSError, UnicodeError, ValueError) as exc:
        return 2, f"lcov-merge-error:{type(exc).__name__}"
    if not functions and not lines and not branches:
        return 2, "lcov-records-missing"
    profile.parent.mkdir(parents=True, exist_ok=True)
    sources = sorted(set(functions_by_source) | set(lines_by_source) | set(branches_by_source))
    with profile.open("w", encoding="utf-8") as stream:
        for source in sources:
            stream.write(f"TN:\nSF:{source}\n")
            source_functions = sorted(functions_by_source.get(source, ()))
            for key in source_functions:
                stream.write(f"FN:{key[1]},{key[2]}\n")
            for key in source_functions:
                stream.write(f"FNDA:{functions[key]},{key[2]}\n")
            stream.write(f"FNF:{len(source_functions)}\n")
            stream.write(f"FNH:{sum(functions[key] > 0 for key in source_functions)}\n")
            source_lines = sorted(lines_by_source.get(source, ()))
            for _, line in source_lines:
                stream.write(f"DA:{line},{lines[(source, line)]}\n")
            stream.write(f"LF:{len(source_lines)}\n")
            stream.write(f"LH:{sum(lines[key] > 0 for key in source_lines)}\n")
            source_branches = sorted(branches_by_source.get(source, ()))
            for _, branch in source_branches:
                hits = branches[(source, branch)]
                stream.write(f"BRDA:{branch},{hits or '-'}\n")
            stream.write(f"BRF:{len(source_branches)}\n")
            stream.write(f"BRH:{sum(branches[key] > 0 for key in source_branches)}\n")
            stream.write("end_of_record\n")
    return 0, ""


def _identity(target: dict[str, Any], spec: dict[str, Any], binary: Path | None) -> dict[str, Any]:
    attestation = _manifest_source_identity(spec)
    current = _git_attestation(_dependency_path(spec.get("source_root")))
    if attestation is not None:
        actual = attestation.get("head") if attestation.get("status") in {"clean", "dirty"} else None
        identity_evidence = attestation.get("evidence") or "wrapper-host-git-attestation-v1"
        start_status = attestation.get("status")
        start_dirty = attestation.get("source_dirty") is True
        start_clean_flag = attestation.get("source_dirty") is False
        start_dirty_paths = attestation.get("non_generated_dirty_paths")
        if not isinstance(start_dirty_paths, list):
            start_dirty_paths = []
        if start_status == "dirty" or start_dirty or start_dirty_paths:
            source_tree_reason = "source-coverage-source-tree-dirty"
        elif not actual or start_status != "clean" or not start_clean_flag:
            source_tree_reason = "source-coverage-source-tree-state-unavailable"
        elif current["status"] == "unavailable":
            # The container may only have the mounted source snapshot, not its
            # Git metadata.  A complete host attestation is the authoritative
            # state for that snapshot; do not relabel it as unknown merely
            # because the container-side checkout cannot be queried.
            source_tree_reason = None
        elif current["head"] != actual:
            source_tree_reason = "source-coverage-source-tree-head-drift"
        elif current["source_dirty"]:
            source_tree_reason = "source-coverage-source-tree-dirty"
        else:
            source_tree_reason = None
        source_tree_status = (
            "dirty" if source_tree_reason == "source-coverage-source-tree-dirty"
            else start_status if current["status"] == "unavailable"
            and start_status in {"clean", "dirty"} else current["status"]
        )
        source_tree_dirty = (
            source_tree_reason == "source-coverage-source-tree-dirty"
            or current["status"] == "unavailable" and start_dirty
        )
        source_tree_dirty_path_count = max(
            _safe_count(attestation.get("dirty_path_count")),
            _safe_count(current.get("dirty_path_count")),
        )
        non_generated_dirty_paths = list(dict.fromkeys(
            [*start_dirty_paths, *current.get("non_generated_dirty_paths", [])]
        ))[:20]
        generated_untracked_path_count = max(
            _safe_count(attestation.get("generated_untracked_path_count")),
            _safe_count(current.get("generated_untracked_path_count")),
        )
    else:
        actual = current["head"]
        source_tree_status = current["status"]
        source_tree_dirty = current["source_dirty"]
        source_tree_reason = (
            "source-coverage-source-tree-state-unavailable"
            if source_tree_status == "unavailable" else
            "source-coverage-source-tree-dirty" if source_tree_dirty else None
        )
        source_tree_dirty_path_count = current["dirty_path_count"]
        non_generated_dirty_paths = current["non_generated_dirty_paths"]
        generated_untracked_path_count = current["generated_untracked_path_count"]
        identity_evidence = "source-root-git"
    expected = spec.get("source_commit")
    source_commit_match = actual == expected if actual and expected else None
    binary_sha256 = _file_sha256(binary)
    expected_binary_sha256 = (
        spec.get("coverage_binary_sha256")
        or target.get("coverage_binary_sha256")
    )
    binary_sha256_match = (
        isinstance(binary_sha256, str)
        and isinstance(expected_binary_sha256, str)
        and binary_sha256.lower() == expected_binary_sha256.lower()
        if binary_sha256 and expected_binary_sha256 else None
    )
    collector = str(spec.get("collector", "gcov"))
    try:
        collector_tools = _collector_tools(spec, collector)
    except OSError as exc:
        collector_tools = {"error": f"{type(exc).__name__}:{exc}"}
    instrumented_binaries = instrumented_binary_identity(spec)
    instrumented_binaries_match = all(
        item.get("sha256_match") is True for item in instrumented_binaries
    )
    return {
        "schema_version": "rq1-simulator-source-profile-identity-v4",
        "backend": target.get("id"),
        "source_repository": spec.get("source_repository"),
        "source_commit": spec.get("source_commit"),
        "target_commit": spec.get("target_commit") or target.get("commit"),
        "source_scope": spec.get("source_scope", []),
        "source_scope_exclude": spec.get("source_scope_exclude", []),
        "source_root": spec.get("source_root"),
        "coverage_binary": target.get("coverage_binary"),
        "source_commit_observed": actual,
        "source_commit_expected": expected,
        "source_commit_match": source_commit_match,
        "coverage_binary_sha256": binary_sha256,
        "coverage_binary_expected_sha256": expected_binary_sha256,
        "coverage_binary_sha256_match": binary_sha256_match,
        # 兼容旧结果字段；这里保存的是源码提交身份，不是 coverage 二进制文件摘要。
        "coverage_binary_sha": actual,
        "coverage_binary_expected_sha": expected,
        "coverage_binary_sha_match": source_commit_match,
        "source_tree_status": source_tree_status,
        "source_tree_dirty": source_tree_dirty,
        "source_tree_drift_reason": source_tree_reason,
        "non_generated_dirty_paths": non_generated_dirty_paths,
        "source_dirty_path_count": source_tree_dirty_path_count,
        "generated_untracked_path_count": generated_untracked_path_count,
        "source_tree_head": attestation.get("head") if attestation else actual,
        "source_identity_evidence": identity_evidence,
        "coverage_binary_present": bool(binary and binary.is_file()),
        "toolchain": spec.get("toolchain"),
        "build_flags": spec.get("build_flags", []),
        "collector": spec.get("collector"),
        "collector_input_format": spec.get("collector_input_format"),
        "collector_tools": collector_tools,
        "instrumented_binaries": instrumented_binaries,
        "instrumented_binaries_match": instrumented_binaries_match,
        "collector_pipeline": SOURCE_COVERAGE_PIPELINE,
    }


def _source_commit_proven_mismatch(identity: dict[str, Any]) -> bool:
    observed = identity.get("source_commit_observed")
    expected = identity.get("source_commit_expected") or identity.get("source_commit")
    target = identity.get("target_commit")
    return bool(
        (observed and expected and observed != expected)
        or (observed and target and observed != target)
        or (expected and target and expected != target)
    )


def _identity_provenance_warnings(identity: dict[str, Any]) -> list[str]:
    warnings = []
    tree_reason = _source_tree_provenance_warning(identity)
    if tree_reason:
        warnings.append(tree_reason)
    if not identity.get("source_commit_observed"):
        warnings.append("source-coverage-source-identity-unavailable")
    if _source_commit_proven_mismatch(identity):
        warnings.append("source-coverage-source-commit-mismatch")
    elif not identity.get("source_commit_expected"):
        warnings.append("source-coverage-source-commit-expected-unavailable")
    return sorted(set(warnings))


def _identity_gap_reason(identity: dict[str, Any]) -> str:
    if _source_commit_proven_mismatch(identity):
        return "source-coverage-source-commit-mismatch"
    expected_binary = identity.get("coverage_binary_expected_sha256")
    observed_binary = identity.get("coverage_binary_sha256")
    if not isinstance(expected_binary, str) or not expected_binary:
        return "source-coverage-binary-sha-not-declared"
    if not isinstance(observed_binary, str) or not observed_binary:
        return "source-coverage-binary-sha-unavailable"
    if observed_binary.lower() != expected_binary.lower():
        return "source-coverage-binary-sha-mismatch"
    if identity.get("instrumented_binaries_match") is False:
        entries = identity.get("instrumented_binaries", [])
        if any(not item.get("expected_sha256") for item in entries
               if isinstance(item, dict)):
            return "source-coverage-instrumented-binary-sha-not-declared"
        if any(not item.get("sha256") for item in entries
               if isinstance(item, dict)):
            return "source-coverage-instrumented-binary-sha-unavailable"
        return "source-coverage-instrumented-binary-sha-mismatch"
    return "source-coverage-profile-empty"


def _source_tree_provenance_warning(identity: dict[str, Any]) -> str | None:
    dirty_paths = identity.get("non_generated_dirty_paths")
    if (identity.get("source_tree_status") == "dirty"
            or identity.get("source_tree_dirty") is True
            or isinstance(dirty_paths, list) and bool(dirty_paths)):
        return "source-coverage-source-tree-dirty"
    drift_reason = identity.get("source_tree_drift_reason")
    if drift_reason:
        return str(drift_reason)
    if (identity.get("source_tree_status") != "clean"
            or identity.get("source_tree_dirty") is not False
            or not isinstance(dirty_paths, list)):
        return "source-coverage-source-tree-state-unavailable"
    return None


